// دالة استخراج الكلمات حسب القسم واللهجة المختارة
function getWordsForCategoryAndDialect(categoryId, dialectId) {
  const category = GAME_CATEGORIES[categoryId];
  if (!category) return [];

  const universalWords = category.words.universal || [];
  const dialectWords = (category.words[dialectId]) || [];

  return [...universalWords, ...dialectWords];
}

// حساب إجمالي الكلمات المتاحة في القسم للهجة الحالية
function getCategoryWordCount(categoryId, dialectId) {
  return getWordsForCategoryAndDialect(categoryId, dialectId).length;
}

// مولّد الخيارات الذكية للتخمين (7 خيارات: 1 صحيحة + 6 مضللة من نفس القسم واللهجة)
function generateGuessOptions(secretWord, categoryId, dialectId) {
  const pool = getWordsForCategoryAndDialect(categoryId, dialectId);
  if (!pool || pool.length === 0) return [secretWord];

  const otherWords = pool.filter(w => w !== secretWord);
  const shuffledOthers = [...otherWords].sort(() => 0.5 - Math.random());
  const selectedDistractors = shuffledOthers.slice(0, 6);

  const allChoices = [secretWord, ...selectedDistractors].sort(() => 0.5 - Math.random());
  return allChoices;
}
